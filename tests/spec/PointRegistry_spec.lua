describe("RsePointRegistry", function()
    local function registry()
        local r = RsePointRegistry.new()
        r:add("Shop", "both", 0, 0, "map")
        r:add("Rendering plant", "disposal", 100, 0, "player")
        r:add("Tow yard", "recovery", 0, 100, "player")
        return r
    end

    it("adds points with increasing ids and rejects bad ones", function()
        local r = RsePointRegistry.new()
        expectEqual(r:add("A", "both", 1, 2), 1)
        expectEqual(r:add("B", "disposal", 3, 4), 2)
        expectNil(r:add("C", "spaceport", 0, 0))
        expectNil(r:add("D", "both", nil, 0))
        expectEqual(#r:list(), 2)
    end)

    it("finds the nearest point that serves a kind", function()
        local r = registry()
        local point, d = r:nearest(90, 0, "disposal")
        expectEqual(point.name, "Rendering plant")
        expectNear(d, 10, 1e-9)
        expectEqual(r:nearest(0, 90, "disposal").name, "Shop", "a recovery point doesn't take carcasses")
        expectEqual(r:nearest(0, 90, "recovery").name, "Tow yard")
    end)

    it("knows when a position is inside a point's radius", function()
        local r = registry()
        expectEqual(r:at(105, 5, "disposal", 12).name, "Rendering plant")
        expectNil(r:at(50, 50, "disposal", 12))
    end)

    it("removes points and lists only player points for saving", function()
        local r = registry()
        expectEqual(#r:playerPoints(), 2)
        expectEqual(r:remove(2).name, "Rendering plant")
        expectNil(r:remove(2))
        expectEqual(#r:playerPoints(), 1)
    end)
end)
