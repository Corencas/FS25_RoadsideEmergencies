describe("RseGuide", function()
    it("has a title and text on every page", function()
        expectTrue(#RseGuide.PAGES > 1, "more than one page")
        for i, page in ipairs(RseGuide.PAGES) do
            expectTrue(type(page.title) == "string", "title of page " .. i)
            expectTrue(#page.lines > 0, "text on page " .. i)
        end
    end)

    it("stops at the first and the last page", function()
        expectEqual(RseGuide.turn(1, -1), 1)
        expectEqual(RseGuide.turn(1, 1), 2)
        expectEqual(RseGuide.turn(#RseGuide.PAGES, 1), #RseGuide.PAGES)
    end)

    it("stops at the last screen once the pages are laid out", function()
        expectEqual(RseGuide.turn(5, 1, 5), 5)
        expectEqual(RseGuide.turn(5, 1, 6), 6)
    end)

    it("keeps a page that fits on one screen", function()
        local screens = RseGuide.layout({ { 10, 10 }, { 30 } }, 40, 5)
        expectEqual(#screens, 2)
        expectEqual(screens[1].first, 1)
        expectEqual(screens[1].last, 2)
        expectEqual(screens[1].parts, 1)
        expectEqual(screens[2].page, 2)
    end)

    it("goes on over the next screen when a page doesn't fit, without splitting a line", function()
        -- 20 + 5 + 20 = 45 fits in 50; the third line would make 70
        local screens = RseGuide.layout({ { 20, 20, 20, 20 } }, 50, 5)
        expectEqual(#screens, 2)
        expectEqual(screens[1].last, 2)
        expectEqual(screens[2].first, 3)
        expectEqual(screens[2].last, 4)
        expectEqual(screens[2].part, 2)
        expectEqual(screens[2].parts, 2)
    end)

    it("gives a line taller than a screen a screen of its own", function()
        local screens = RseGuide.layout({ { 10, 90, 10 } }, 50, 5)
        expectEqual(#screens, 3)
        expectEqual(screens[2].first, 2)
        expectEqual(screens[2].last, 2)
        expectEqual(screens[3].first, 3)
    end)

    it("remembers that the guide has been shown, in the store and the savegame", function()
        local store = RseStore.new(RseConfig)
        store:apply("setGuideSeen", { seen = true })
        expectEqual(store.settings.guideSeen, true)
        expectEqual(RseSaveCodec.normalize({ settings = { guideSeen = true } }, RseConfig).settings.guideSeen, true)
        expectEqual(RseSaveCodec.normalize({ settings = {} }, RseConfig).settings.guideSeen, false, "a new savegame sees it")
    end)
end)
