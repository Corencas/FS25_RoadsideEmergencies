describe("RseAnimalCatalog", function()
    it("returns a copy with its kind and text key", function()
        local deer = RseAnimalCatalog.get("deer")
        expectEqual(deer.kind, "deer")
        expectEqual(deer.textKey, "rse_animal_deer")
        expectEqual(deer.massKg, 80)
        deer.massKg = 1
        expectEqual(RseAnimalCatalog.get("deer").massKg, 80, "the catalog itself is unchanged")
    end)

    it("gives every animal its own fill type (own name and picture)", function()
        expectEqual(RseAnimalCatalog.get("deer").fillTypeName, "RSE_CARCASS_DEER")
        expectEqual(RseAnimalCatalog.get("Buffalo").fillTypeName, "RSE_CARCASS_BUFFALO")
    end)

    it("accepts any letter case and rejects unknown kinds", function()
        expectEqual(RseAnimalCatalog.get("COW").kind, "cow")
        expectNil(RseAnimalCatalog.get("dragon"))
        expectNil(RseAnimalCatalog.get(nil))
    end)

    it("lists all eight kinds, sorted", function()
        local kinds = RseAnimalCatalog.kinds()
        expectEqual(#kinds, 8)
        expectEqual(kinds[1], "boar")
        expectEqual(kinds[8], "sheep")
    end)

    it("lets small animals be dragged and big ones not", function()
        expectTrue(RseAnimalCatalog.isDraggable("deer", RseConfig.DRAG_MAX_MASS_KG))
        expectTrue(not RseAnimalCatalog.isDraggable("cow", RseConfig.DRAG_MAX_MASS_KG))
        expectTrue(not RseAnimalCatalog.isDraggable("dragon", RseConfig.DRAG_MAX_MASS_KG))
    end)

    it("puts large animals on the large body and small ones on the small body", function()
        expectEqual(RseAnimalCatalog.get("horse").body, RseAnimalCatalog.BODY_LARGE)
        expectEqual(RseAnimalCatalog.get("goat").body, RseAnimalCatalog.BODY_SMALL)
    end)

    it("lays the model on its side with its underside on the body's underside", function()
        local cow = RseAnimalCatalog.get("cow")
        local rotZ, x, y, z = RseAnimalCatalog.pose(cow, 0.9)
        expectNear(rotZ, math.pi / 2, 1e-9)
        expectNear(x, 0.75, 1e-9)
        expectNear(y, -0.1, 1e-9)
        expectEqual(z, 0)
    end)
end)
