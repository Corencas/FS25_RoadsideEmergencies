describe("RseStore", function()
    it("adds and delivers a carcass, working out the pay and fee once", function()
        local store = RseStore.new(RseConfig)
        local seen = {}
        store:subscribe(function(kind)
            table.insert(seen, kind)
        end)
        local id = store:apply("addCarcass", { kind = "deer" })
        expectEqual(id, 1)
        expectEqual(store:carcassCount(), 1)
        local result = store:apply("deliverCarcass", { id = id, pointName = "Shop" })
        expectEqual(result.pay, 209)
        expectEqual(result.fee, 45)
        expectEqual(result.record.kind, "deer")
        expectEqual(store:carcassCount(), 0)
        expectEqual(table.concat(seen, ","), "addCarcass,deliverCarcass")
    end)

    it("bills the disposal fee and the collection charge for a carcass left behind", function()
        local store = RseStore.new(RseConfig)
        local id = store:apply("addCarcass", { kind = "cow" })
        local result = store:apply("collectCarcass", { id = id })
        expectEqual(result.fee, 188)
        expectEqual(result.charge, 263)
        expectEqual(result.unearned, 0)
        expectEqual(result.total, 451)
        expectEqual(store:carcassCount(), 0)
        expectNil(store:apply("collectCarcass", { id = id }), "only once")
    end)

    it("takes back pay for hauling an animal that was never delivered", function()
        local store = RseStore.new(RseConfig)
        local id = store:apply("addCarcass", { kind = "deer" })
        local result = store:apply("collectCarcass", { id = id, unearned = 570 })
        expectEqual(result.unearned, 570)
        expectEqual(result.total, 735)
    end)

    it("switches calls on and off", function()
        local store = RseStore.new(RseConfig)
        expectEqual(store.settings.callsEnabled, true)
        expectEqual(store:apply("setCallsEnabled", { enabled = false }), false)
        expectEqual(store.settings.callsEnabled, false)
    end)

    it("takes only the known job sizes", function()
        local store = RseStore.new(RseConfig)
        expectEqual(store.settings.jobSize, "normal")
        expectEqual(store:apply("setJobSize", { size = "large" }), "large")
        expectEqual(store.settings.jobSize, "large")
        expectNil(store:apply("setJobSize", { size = "huge" }))
        expectEqual(store.settings.jobSize, "large")
    end)

    it("owes kit items of a job once it ended, not those of other jobs or none", function()
        local store = RseStore.new(RseConfig)
        local a = store:apply("addKitItem", { item = "cone", sceneId = 7 })
        local b = store:apply("addKitItem", { item = "barricade", sceneId = 7 })
        store:apply("addKitItem", { item = "cone", sceneId = 8 })
        store:apply("addKitItem", { item = "cone" })
        expectEqual(store:kitOwedCount(), 0, "the job is still running")
        expectEqual(store:apply("kitJobEnded", { sceneId = 7 }), 2)
        expectEqual(store:kitOwedCount(), 2)
        store:apply("removeKitItem", { id = a })
        store:apply("removeKitItem", { id = b })
        expectEqual(store:kitOwedCount(), 0)
        expectNil(store:apply("addKitItem", { item = "concrete" }), "not in the kit")
    end)

    it("moves the items of a saved job to the scene it has after loading", function()
        local store = RseStore.new(RseConfig)
        store:apply("addKitItem", { item = "cone", sceneId = "resume" })
        expectEqual(store:apply("kitMoveJob", { from = "resume", to = 3 }), 1)
        expectEqual(store:kitOwedCount(), 0)
        expectEqual(store:apply("kitJobEnded", { sceneId = 3 }), 1)
        expectEqual(store:kitOwedCount(), 1)
    end)

    it("uses the income setting for the haul-off pay", function()
        local store = RseStore.new(RseConfig)
        expectEqual(store:apply("setSetting", { key = "payFactor", value = 2 }).value, 2)
        local id = store:apply("addCarcass", { kind = "cow" })
        local result = store:apply("deliverCarcass", { id = id })
        expectEqual(result.pay, 1615)
        expectEqual(result.fee, 188)
    end)

    it("takes only known settings and values", function()
        local store = RseStore.new(RseConfig)
        expectNil(store:apply("setSetting", { key = "payFactor", value = 99 }))
        expectNil(store:apply("setSetting", { key = "nonsense", value = 1 }))
        expectEqual(store.settings.payFactor, 1)
        expectEqual(store:apply("setSetting", { key = "wreckCalls", value = false }).value, false)
        expectEqual(store.settings.wreckCalls, false)
    end)

    it("uses the fee setting", function()
        local store = RseStore.new(RseConfig)
        expectEqual(store:apply("setFeeFactor", { factor = 2 }), 2)
        local id = store:apply("addCarcass", { kind = "cow" })
        local result = store:apply("deliverCarcass", { id = id })
        expectEqual(result.pay, 808, "the fee setting leaves the pay alone")
        expectEqual(result.fee, 375)
    end)

    it("refuses unknown animals, unknown carcasses and unknown changes without telling listeners", function()
        local store = RseStore.new(RseConfig)
        local calls = 0
        store:subscribe(function()
            calls = calls + 1
        end)
        local result, reason = store:apply("addCarcass", { kind = "dragon" })
        expectNil(result)
        expectTrue(reason ~= nil)
        expectNil(store:apply("deliverCarcass", { id = 42 }))
        expectNil(store:apply("launchRocket", {}))
        expectEqual(calls, 0)
    end)

    it("removes player points but keeps map points", function()
        local store = RseStore.new(RseConfig)
        local mapId = store:apply("addPoint", { name = "Shop", kind = "both", x = 0, z = 0, source = "map" })
        local playerId = store:apply("addPoint", { name = "Yard", kind = "disposal", x = 5, z = 5, source = "player" })
        expectNil(store:apply("removePoint", { id = mapId }))
        expectEqual(store:apply("removePoint", { id = playerId }).name, "Yard")
        expectEqual(#store.points:list(), 1)
    end)
end)
